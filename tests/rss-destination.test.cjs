'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const src = fs.readFileSync('worker.js', 'utf8');
const begin = src.indexOf('function isPublicFeedUrl(');
const end = src.indexOf('async function fetchNewsFeedItems(', begin);
assert(begin >= 0 && end > begin, 'RSS guards must exist');
const calls = [];
let responder = async () => ({status:200,ok:true,headers:{get:()=>null}});
const context = {URL, fetch:async (url,opts)=>{calls.push({url,opts});return responder(url,opts);},Error};
vm.createContext(context);
vm.runInContext(src.slice(begin,end),context);
const allowed = ['https://www.bbc.com/news/rss.xml','http://feeds.bbci.co.uk/news/rss.xml','https://feeds.feedburner.com/Example','https://news.google.com/rss/search?q=stocks','https://example.com./feed'];
const denied = ['http://localhost/a','http://127.0.0.1/a','http://[::1]/','http://169.254.169.254/latest','http://0x7f000001/','https://metadata.google.internal/','file:///etc/passwd','https://example.com:8080/rss','https://user:pass@example.com/feed','https://127.1/rss','https://2130706433/rss','https://example.com@127.0.0.1/'];
(async()=>{
for(const url of allowed) assert.equal(context.isPublicFeedUrl(url),true,'should allow '+url);
for(const url of denied) assert.equal(context.isPublicFeedUrl(url),false,'should block '+url);
responder=async (url)=>url==='https://publisher.example/rss'?{status:302,headers:{get:()=>'/new-rss'}}:{status:200,headers:{get:()=>null}};
calls.length=0;
const response=await context.fetchPublicFeed('https://publisher.example/rss',{headers:{Accept:'application/rss+xml'}});
assert.equal(response.status,200);
assert.equal(calls.length,2);
assert.equal(calls[1].url,'https://publisher.example/new-rss');
assert(calls.every(c=>c.opts.redirect==='manual'));
responder=async()=>({status:302,headers:{get:()=> 'http://127.0.0.1/private'}});
calls.length=0;
await assert.rejects(context.fetchPublicFeed('https://publisher.example/rss',{}),/Unsafe feed destination/);
assert.equal(calls.length,1,'private redirect must not be fetched');
responder=async()=>({status:302,headers:{get:()=> '/loop'}});
calls.length=0;
await assert.rejects(context.fetchPublicFeed('https://publisher.example/rss',{}),/Invalid feed redirect/);
assert.equal(calls.length,6,'redirect limit');
console.log('RSS URL/redirect tests passed');
})().catch(e=>{console.error(e);process.exitCode=1});
